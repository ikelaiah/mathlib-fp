#!/usr/bin/env python3
"""Regenerate analytic offset/exposure fixtures with 80-digit Decimal arithmetic."""
from decimal import Decimal as D, localcontext
from pathlib import Path

with localcontext() as context:
    context.prec = 80
    values = {
        'GLMExposureNullDeviance': 2*(2*(D(2)/D('4.5')).ln()
            +8*(D(8)/9).ln()+8*(D(8)/D('4.5')).ln()),
        'GLMExposureInterceptError': (D(40)/144).sqrt(),
        'GLMExposureSlopeError': (D(18)/144).sqrt(),
        'GLMOffsetLogisticDeviance': -8*D('.75').ln(),
        'GLMOffsetLogisticError': (D(4)/3).sqrt(),
    }
    text = '{ Analytic likelihood/information identities; 80-digit Decimal.\n' \
        '  Generated by tools/generate_glm_offset_reference.py; MIT. }\nconst\n'
    text += ''.join(f'  {name}: Double = {value};\n' for name,value in values.items())
    target = Path(__file__).resolve().parent.parent/'tests/GLMOffsetReference.inc'
    target.write_text(text, encoding='utf-8')
    print('Wrote', target)
