#!/usr/bin/env python3
"""Generate independent high-precision SOS coefficient references."""

from __future__ import annotations

import argparse
from decimal import Decimal, getcontext
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests" / "SOSIIRReference.inc"
getcontext().prec = 100
D = Decimal
PI = D(
    "3.141592653589793238462643383279502884197169399375105820974944592307816406286208998628034825342117068"
)


def sin_cos(value: Decimal) -> tuple[Decimal, Decimal]:
    value %= 2 * PI
    if value > PI:
        value -= 2 * PI
    square = value * value
    sin_term = sin_value = value
    cos_term = cos_value = D(1)
    for k in range(1, 160):
        sin_term *= -square / D((2 * k) * (2 * k + 1))
        cos_term *= -square / D((2 * k - 1) * (2 * k))
        sin_value += sin_term
        cos_value += cos_term
        if abs(sin_term) < D("1e-98") and abs(cos_term) < D("1e-98"):
            break
    return sin_value, cos_value


def tan(value: Decimal) -> Decimal:
    sine, cosine = sin_cos(value)
    return sine / cosine


def fmt(value: Decimal) -> str:
    if value == 0:
        return "0.0"
    return f"{value:.55E}".replace("E", "e")


def butterworth_second_order() -> list[Decimal]:
    sample_rate, cutoff = D(1000), D(100)
    warped = tan(PI * cutoff / sample_rate)
    root_two = D(2).sqrt()
    normalizer = 1 / (1 + root_two * warped + warped * warped)
    b0 = warped * warped * normalizer
    return [
        b0,
        2 * b0,
        b0,
        2 * (warped * warped - 1) * normalizer,
        (1 - root_two * warped + warped * warped) * normalizer,
    ]


def chebyshev_first_order() -> list[Decimal]:
    sample_rate, cutoff, ripple_db = D(1000), D(100), D(1)
    epsilon = ((ripple_db * D(10).ln() / 10).exp() - 1).sqrt()
    warped = tan(PI * cutoff / sample_rate)
    analog_pole_magnitude = warped / epsilon
    digital_pole = (1 - analog_pole_magnitude) / (1 + analog_pole_magnitude)
    a1 = -digital_pole
    b0 = (1 + a1) / 2
    return [b0, b0, D(0), a1, D(0)]


def chebyshev_second_order() -> list[Decimal]:
    sample_rate, cutoff, ripple_db = D(1000), D(100), D(1)
    epsilon = ((ripple_db * D(10).ln() / 10).exp() - 1).sqrt()
    mu = (1 / epsilon + (1 / (epsilon * epsilon) + 1).sqrt()).ln() / 2
    warped = tan(PI * cutoff / sample_rate)
    root_two = D(2).sqrt()
    positive_exp, negative_exp = mu.exp(), (-mu).exp()
    sinh_mu = (positive_exp - negative_exp) / 2
    cosh_mu = (positive_exp + negative_exp) / 2
    pole_real = -sinh_mu / root_two
    pole_imag = cosh_mu / root_two
    scaled_real, scaled_imag = warped * pole_real, warped * pole_imag
    denominator = (1 - scaled_real) ** 2 + scaled_imag**2
    digital_real = (1 - scaled_real**2 - scaled_imag**2) / denominator
    digital_imag = 2 * scaled_imag / denominator
    a1 = -2 * digital_real
    a2 = digital_real**2 + digital_imag**2
    passband_minimum = (-ripple_db * D(10).ln() / 20).exp()
    b0 = passband_minimum * (1 + a1 + a2) / 4
    return [b0, 2 * b0, b0, a1, a2]


def butterworth_response() -> list[Decimal]:
    """Return independent complex response values for the 2nd-order fixture."""
    coefficients = butterworth_second_order()
    sample_rate = D(1000)
    response: list[Decimal] = []
    for frequency in (D(0), D(50), D(100), D(250), D(500)):
        angle = 2 * PI * frequency / sample_rate
        sine, cosine = sin_cos(angle)
        sine2, cosine2 = sin_cos(2 * angle)
        numerator_real = (
            coefficients[0] + coefficients[1] * cosine
            + coefficients[2] * cosine2
        )
        numerator_imag = -(
            coefficients[1] * sine + coefficients[2] * sine2
        )
        denominator_real = (
            D(1) + coefficients[3] * cosine + coefficients[4] * cosine2
        )
        denominator_imag = -(
            coefficients[3] * sine + coefficients[4] * sine2
        )
        denominator_norm = denominator_real**2 + denominator_imag**2
        response.append(
            (numerator_real * denominator_real
             + numerator_imag * denominator_imag) / denominator_norm
        )
        response.append(
            (numerator_imag * denominator_real
             - numerator_real * denominator_imag) / denominator_norm
        )
    return response


def render() -> str:
    references = (
        ("SOSButterworth2LowPassReference", butterworth_second_order()),
        ("SOSChebyshev1LowPassReference", chebyshev_first_order()),
        ("SOSChebyshev2LowPassReference", chebyshev_second_order()),
        ("SOSButterworth2LowPassResponseReference", butterworth_response()),
    )
    lines = [
        "{ Generated by tools/generate_sos_iir_reference.py using Python Decimal, 100-digit context. }",
        "{ Values are B0, B1, B2, A1, A2; formulas are documented in the generator. }",
        "const",
    ]
    for name, values in references:
        lines.append(f"  {name}: array[0..{len(values) - 1}] of Double = (")
        lines.append("    " + ",\n    ".join(fmt(value) for value in values) + ");")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"reference fixture is stale: regenerate {OUTPUT}")
        print(f"reference fixture is current: {OUTPUT.relative_to(ROOT)}")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
