#!/usr/bin/env python3
"""Independent fixed version-1 legacy model envelopes (stdlib struct/zlib)."""
from pathlib import Path
import struct
import zlib

def vector(values):
    return struct.pack('<Q', len(values))+struct.pack('<'+'d'*len(values), *values)
def envelope(kind, payload):
    return b'MFPMOD1\0'+struct.pack('<HBBQI',1,kind,0,len(payload),zlib.crc32(payload))+payload

fixtures = {
    'LegacySplineHex': envelope(1,b'\0'+vector([0,1])+vector([0,1])
        +vector([1])+vector([0])+vector([0])),
    'LegacyFIRHex': envelope(2,vector([.25,.5,.25])+vector([2,1])),
    'LegacyStandardizationHex': envelope(3,vector([3])+vector([2])),
    'LegacyKalmanHex': envelope(4,struct.pack('<6d',1,1,.1,.2,3,.4)),
}
text='{ Independent legacy model v1 fixtures; struct little-endian and zlib CRC32.\n' \
     '  Generated by tools/generate_prediction_legacy_fixtures.py; MIT. }\nconst\n'
for name, value in fixtures.items():
    encoded=value.hex().upper()
    chunks=[encoded[i:i+96] for i in range(0,len(encoded),96)]
    text+='  '+name+' =\n    '+" +\n    ".join("'"+s+"'" for s in chunks)+';\n'
target=Path(__file__).resolve().parent.parent/'tests/PredictionLegacyFixtures.inc'
target.write_text(text,encoding='utf-8')
print('Wrote',target)
