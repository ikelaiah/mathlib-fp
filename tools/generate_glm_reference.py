#!/usr/bin/env python3
"""Independent 90-digit GLM fixtures using Newton normal equations.

Repository-authored MIT code; only Python's standard library is needed.
The production implementation uses binary64 pivoted QR instead. Family/link
and deviance definitions: https://www.statsmodels.org/stable/glm.html
"""
from __future__ import annotations

import argparse
from decimal import Decimal as D, localcontext
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "tests" / "GLMReference.inc"


def solve(a, b):
    a = [list(row) + [rhs] for row, rhs in zip(a, b)]
    n = len(b)
    for j in range(n):
        pivot = max(range(j, n), key=lambda i: abs(a[i][j]))
        a[j], a[pivot] = a[pivot], a[j]
        scale = a[j][j]
        if not scale:
            raise ArithmeticError("singular reference information")
        a[j] = [v / scale for v in a[j]]
        for i in range(n):
            if i != j:
                scale = a[i][j]
                a[i] = [u - scale * v for u, v in zip(a[i], a[j])]
    return [row[-1] for row in a]


def evaluate(family, x, y, beta):
    eta = [sum(v * b for v, b in zip(row, beta)) for row in x]
    mu = [1 / (1 + (-v).exp()) if family == 0 else v.exp() for v in eta]
    weights = [v * (1 - v) if family == 0 else v for v in mu]
    if family == 0:
        dev = -2 * sum(t * m.ln() + (1 - t) * (1 - m).ln() for t, m in zip(y, mu))
    else:
        dev = 2 * sum((t * (t.ln() - v) if t else D(0)) - t + m
                      for t, m, v in zip(y, mu, eta))
    return mu, weights, dev


def reference(family, raw_x, raw_y):
    x = [[D(str(v)) for v in row] for row in raw_x]
    y = [D(str(v)) for v in raw_y]
    p = len(x[0])
    beta = [D(0)] * p
    for _ in range(200):
        mu, weights, dev = evaluate(family, x, y, beta)
        info = [[sum(w * row[j] * row[k] for row, w in zip(x, weights))
                 for k in range(p)] for j in range(p)]
        score = [sum(row[j] * (t - m) for row, t, m in zip(x, y, mu))
                 for j in range(p)]
        delta = solve(info, score)
        if max(map(abs, delta)) < D("1e-75"):
            break
        step = D(1)
        while True:
            candidate = [b + step * d for b, d in zip(beta, delta)]
            if evaluate(family, x, y, candidate)[2] <= dev + D("1e-80"):
                beta = candidate
                break
            step /= 2
            if step < D("1e-30"):
                raise ArithmeticError("reference line search stalled")
    else:
        raise ArithmeticError("reference Newton iteration limit")
    mu, weights, dev = evaluate(family, x, y, beta)
    info = [[sum(w * row[j] * row[k] for row, w in zip(x, weights))
             for k in range(p)] for j in range(p)]
    se = [solve(info, [D(int(k == j)) for k in range(p)])[j].sqrt()
          for j in range(p)]
    pearson = sum((t - m) ** 2 / w for t, m, w in zip(y, mu, weights))
    return beta, se, mu, dev, pearson


def generate():
    x = [[1, i // 2 - 2, -1 if i % 2 == 0 else 1] for i in range(12)]
    cases = [
        (0, [[1]] * 6, [0, 0, 1, 1, 1, 1]),
        (1, [[1]] * 6, [0, 1, 2, 3, 4, 2]),
        (0, [row[:2] for row in x], [0, 1, 0, 0, 0, 1, 1, 0, 1, 1, 1, 0]),
        (0, x, [0, 1, 0, 0, 0, 1, 1, 0, 1, 1, 1, 0]),
        (1, x, [0, 1, 0, 2, 1, 3, 2, 2, 3, 4, 2, 5]),
        (1, [[row[0], row[1] * 1000000, row[2] / 1000] for row in x],
         [0, 1, 0, 2, 1, 3, 2, 2, 3, 4, 2, 5]),
    ]

    def values(items, size):
        return "(" + ", ".join(format(float(v), ".17g") for v in
                                list(items) + [0] * (size - len(items))) + ")"

    lines = ["{ Generated by tools/generate_glm_reference.py; 90-digit Decimal.",
             "  Independent Newton normal equations; repository-authored MIT. }",
             "type", "  TGLMReferenceCase = record", "    Family, N, P: Integer;",
             "    Design: array[0..35] of Double;", "    Response, Means: array[0..11] of Double;",
             "    Coefficients, Errors: array[0..2] of Double;",
             "    Deviance, Pearson: Double;", "  end;", "const",
             "  GLMReferences: array[0..5] of TGLMReferenceCase = ("]
    with localcontext() as ctx:
        ctx.prec = 90
        for index, (family, design, response) in enumerate(cases):
            beta, se, mu, dev, pearson = reference(family, design, response)
            lines += [f"    (Family: {family}; N: {len(design)}; P: {len(design[0])};",
                      "     Design: " + values([v for row in design for v in row], 36) + ";",
                      "     Response: " + values(response, 12) + ";",
                      "     Means: " + values(mu, 12) + ";",
                      "     Coefficients: " + values(beta, 3) + ";",
                      "     Errors: " + values(se, 3) + ";",
                      f"     Deviance: {float(dev):.17g}; Pearson: {float(pearson):.17g})"
                      + ("," if index < len(cases) - 1 else "")]
    return "\n".join(lines + ["  );", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != content:
            raise SystemExit("GLM reference fixture is stale")
        print("GLM reference fixtures verified (90-digit Decimal)")
    else:
        DEST.write_text(content, encoding="utf-8", newline="\n")
        print(f"Generated {DEST.relative_to(ROOT)}")
